      <h3>How each technology works</h3>
      <p><strong>Service Deionization (SDI)</strong> uses ion exchange resin beads to chemically remove dissolved ions from water. Cation resin captures positive ions; anion resin captures negative ions. A mixed-bed configuration polishes water to near-pure resistivity. Tanks are swapped when resin is exhausted — regeneration happens off-site.</p>
      <p style="margin-top:0.75rem;"><strong>Reverse Osmosis (RO)</strong> forces water under pressure through a semi-permeable membrane that physically blocks most dissolved solids, bacteria, and organics. The membrane rejects 90–99% of contaminants and sends a concentrate stream to drain.</p>
    </article>

    <article class="card">
      <h3>What each system removes</h3>
      <ul class="bullets">
        <li><strong>SDI:</strong> Virtually all dissolved ions (cations and anions) — achieves near-zero conductivity / 1–18 MegOhm resistivity</li>
        <li><strong>RO:</strong> ~90–99% of dissolved solids, plus bacteria, pyrogens, and larger organics — but does not achieve DI-level purity alone</li>
        <li><strong>SDI does NOT remove:</strong> bacteria, organics, particles (pretreatment and filters address these)</li>
        <li><strong>RO does NOT fully remove:</strong> dissolved gases, some small organics, or achieve ultra-low conductivity without polishing</li>
      </ul>
    </article>

    <article class="card">
      <h3>Purity output comparison</h3>
      <ul class="bullets">
        <li><strong>Municipal tap water:</strong> ~200–500 µS/cm conductivity (high ion content)</li>
        <li><strong>After RO:</strong> typically 1–10 µS/cm (90–99% ion removal)</li>
        <li><strong>After DI (two-bed):</strong> typically 0.1–2 µS/cm</li>
        <li><strong>After mixed-bed DI:</strong> typically &lt;0.1 µS/cm (1–18 MegOhm resistivity)</li>
        <li><strong>After RO + mixed-bed DI:</strong> highest achievable purity in a service-based model</li>
      </ul>
