    <div class="cards">
      <article class="card">
        <h3>What is ion exchange?</h3>
        <p>Ion exchange resin is a synthetic polymer bead that carries a charge. When water flows through the resin bed, dissolved ions in the water swap places with ions on the resin — effectively removing them from the water. Cation resin swaps hydrogen (H⁺) for dissolved positive ions like calcium (Ca²⁺), magnesium (Mg²⁺), and sodium (Na⁺). Anion resin swaps hydroxyl (OH⁻) for dissolved negative ions like chloride (Cl⁻), sulfate (SO₄²⁻), and bicarbonate (HCO₃⁻).</p>
        <a class="link" href="how-sdi-works.php">Full SDI explainer →</a>
      </article>
      <article class="card">
        <h3>What happens in a mixed bed?</h3>
        <p>In a mixed-bed tank, cation and anion resin beads are intimately mixed together. As water travels through the bed, each water molecule encounters both resin types repeatedly — hundreds or thousands of exchanges per pass. This produces extremely thorough ion removal and very high purity output. The H⁺ and OH⁻ ions released recombine to form water (H₂O), leaving no ionic byproduct.</p>
      </article>
      <article class="card">
        <h3>What is resistivity and why does it matter?</h3>
        <p>Resistivity (measured in MegOhm·cm or ohm·cm) is the standard measure of water purity in deionization — it's the inverse of conductivity. Pure water with no dissolved ions has a theoretical maximum resistivity of 18.2 MegOhm·cm at 25°C. The more ions present, the lower the resistivity. A mixed-bed DI system fresh from regeneration will typically produce 5–18 MegOhm water; as resin exhausts, resistivity drops toward the minimum acceptable level for your application.</p>
