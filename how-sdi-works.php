      <h3>The core idea</h3>
      <p>Water from the municipal supply or a well contains dissolved minerals — calcium, magnesium, sodium, chloride, sulfate, and more. For many industrial and laboratory applications, those dissolved solids interfere with your process, damage equipment, or produce unacceptable results.</p>
      <p style="margin-top:0.75rem;">Service deionization removes those dissolved ions using ion exchange resin. The result is high-purity deionized (DI) water — free of the minerals that cause scaling, spotting, contamination, and inconsistency.</p>
    </article>

    <article class="card">
      <h3>How ion exchange resin works</h3>
      <p>Resin beads inside the tank carry a charge. As water flows through:</p>
      <ul class="bullets">
        <li><strong>Cation resin</strong> captures positive ions — calcium, magnesium, sodium, potassium — and releases hydrogen (H⁺) in exchange</li>
        <li><strong>Anion resin</strong> captures negative ions — chloride, sulfate, nitrate, silica — and releases hydroxide (OH⁻) in exchange</li>
        <li>The H⁺ and OH⁻ combine to form pure water (H₂O)</li>
      </ul>
      <p style="margin-top:0.75rem;">As the resin captures more and more ions, it eventually reaches capacity and can no longer produce water at the target quality. This is when the tank is exhausted and needs to be replaced or regenerated.</p>
    </article>

    <article class="card">
      <h3>Cation, anion, and mixed-bed — what's the difference?</h3>
      <ul class="bullets">
        <li><strong>Cation tank:</strong> Removes hardness and metals. First stage in a series system.</li>
        <li><strong>Anion tank:</strong> Removes chloride, sulfate, and other negative ions. Second stage.</li>
        <li><strong>Mixed-bed tank:</strong> Both cation and anion resin blended together. Highest purity output — used as a polisher or standalone for critical applications.</li>
      </ul>
      <p style="margin-top:0.75rem;">Many SDI programs use a cation and anion tank in series, followed by a mixed-bed polisher. Others use mixed-bed only for simplicity when volumes are moderate.</p>
    </article>

    <article class="card">
      <h3>What purity levels can SDI achieve?</h3>
      <ul class="bullets">
        <li><strong>Two-bed (cation + anion):</strong> typically 50 k–500 k ohm-cm resistivity (2–20 µS/cm conductivity)</li>
        <li><strong>Mixed-bed polisher:</strong> typically 1–18 MegOhm resistivity (&lt;0.1 µS/cm)</li>
        <li><strong>ASTM Type II water:</strong> achievable with a well-maintained mixed-bed system</li>
        <li><strong>ASTM Type I / ultra-pure:</strong> requires additional polishing (UV, membrane filtration) — contact us to discuss</li>
      </ul>
      <p style="margin-top:0.75rem;">The right target depends on your application. CNC rinsing typically needs 0.5–2 MegOhm. Labs preparing reagents or running analytical instruments may require 10–18 MegOhm.</p>
    </article>

    <article class="card">
      <h3>What a service deionization (SDI) program looks like</h3>
      <ul class="bullets">
        <li>Pre-filled, freshly regenerated tanks are delivered to your facility on a schedule</li>
        <li>Tanks connect to your existing water line with standard fittings</li>
        <li>A resistivity/conductivity monitor on the outlet tracks water quality in real time</li>
        <li>When resistivity drops toward your minimum acceptable level, a swap is scheduled</li>
        <li>The exhausted tank is picked up; a fresh one is delivered — no chemicals, no downtime</li>
        <li>Regeneration happens off-site at a certified facility</li>
      </ul>
    </article>

    <article class="card">
      <h3>Why SDI over on-site regeneration?</h3>
      <ul class="bullets">
        <li>No acid or caustic chemicals on-site — safer for staff and the facility</li>
        <li>No wastewater neutralization or discharge compliance to manage</li>
        <li>No specialized operators required</li>
        <li>Predictable cost per exchange — easier to budget</li>
        <li>Scales easily — add tanks if demand increases, reduce when it drops</li>
      </ul>
      <p style="margin-top:0.75rem;">On-site regeneration makes sense for very high-volume, continuous operations. For most Canadian industrial and laboratory users, SDI delivers better total cost and less operational risk.</p>
