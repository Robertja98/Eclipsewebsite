      <ol style="padding-left:1.2rem;line-height:2;">
        <li><strong>Feed water TDS</strong> — The total dissolved solids in your input water. Higher TDS = more ions for resin to capture = faster exhaustion. This is the single biggest variable.</li>
        <li><strong>Flow rate and daily usage</strong> — The more water you push through the tank per day, the faster resin exhausts. A system running 8 hours a day exhausts at half the rate of one running 16 hours.</li>
        <li><strong>Resin volume (tank size)</strong> — Larger tanks hold more resin and last longer between exchanges. Sizing matters: an undersized tank for your demand is the most common cause of unexpectedly frequent swaps.</li>
        <li><strong>Target water quality</strong> — If you need 10 MegOhm water, you'll trigger a swap sooner than a facility that accepts 0.5 MegOhm. Higher quality targets mean less usable capacity from each tank.</li>
